//! Generate a compact SVG and percentile table directly from versioned raw data.
use anyhow::{Context, Result, ensure};
use serde_json::Value;
use std::{collections::BTreeMap, env, fs, path::PathBuf};

#[derive(Default)]
struct Samples {
    create: Vec<f64>,
    total: Vec<f64>,
    first: Vec<f64>,
    warm: Vec<f64>,
    modified: Vec<f64>,
    errors: usize,
    incorrect: usize,
}
fn main() -> Result<()> {
    let path = PathBuf::from(
        env::args_os()
            .nth(1)
            .context("usage: twig-plot bench/results/run.json")?,
    );
    let run: Value = serde_json::from_slice(&fs::read(&path)?)?;
    ensure!(
        run["schemaVersion"] == 1 || run["schemaVersion"] == 2,
        "unsupported result schema"
    );
    let mut groups: BTreeMap<(u64, String), Samples> = BTreeMap::new();
    for point in run["points"].as_array().context("missing points")? {
        let key = (
            point["concurrency"].as_u64().context("concurrency")?,
            point["backend"].as_str().context("backend")?.to_owned(),
        );
        let samples = groups.entry(key).or_default();
        for operation in point["operations"].as_array().context("operations")? {
            if !operation["error"].is_null() {
                samples.errors += 1;
            }
            if operation["correct"] != true {
                samples.incorrect += 1;
                continue;
            }
            let metric = |name: &str| {
                operation[name]
                    .as_f64()
                    .with_context(|| format!("missing {name}"))
            };
            let create = metric("createMs")?;
            let first = metric("firstStatusMs")?;
            samples.create.push(create);
            samples.first.push(first);
            samples.total.push(create + first);
            samples.warm.push(metric("warmStatusMs")?);
            samples.modified.push(metric("modifiedStatusMs")?);
        }
    }
    let mut markdown = String::from(
        "<!-- Generated by twig-plot from the adjacent JSON; do not edit. -->\n\n| backend | concurrency | n | metric | p50 ms | p95 ms | p99 ms | max ms | errors | incorrect |\n|---|---:|---:|---|---:|---:|---:|---:|---:|---:|\n",
    );
    for ((concurrency, backend), samples) in &groups {
        for (metric, values) in [
            ("create", &samples.create),
            ("create + first status", &samples.total),
            ("first status", &samples.first),
            ("warm status", &samples.warm),
            ("modified status", &samples.modified),
        ] {
            markdown.push_str(&format!("| {backend} | {concurrency} | {} | {metric} | {:.2} | {:.2} | {:.2} | {:.2} | {} | {} |\n", values.len(), percentile(values, 0.5), percentile(values, 0.95), percentile(values, 0.99), percentile(values, 1.0), samples.errors, samples.incorrect));
        }
    }
    let maximum = groups
        .values()
        .map(|s| percentile(&s.total, 0.5))
        .fold(1.0, f64::max)
        * 1.1;
    let height = 110 + groups.len() * 52;
    let mut svg = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"900\" height=\"{height}\" viewBox=\"0 0 900 {height}\"><rect width=\"100%\" height=\"100%\" fill=\"#111827\"/><g font-family=\"system-ui,sans-serif\" fill=\"#e5e7eb\"><text x=\"24\" y=\"30\" font-size=\"19\">Worktree creation + first status · median milliseconds</text><text x=\"24\" y=\"53\" font-size=\"12\">Local warm-cache CLI runs · lower is better · see JSON for provenance and errors</text>"
    );
    for (index, ((concurrency, backend), samples)) in groups.iter().enumerate() {
        let value = percentile(&samples.total, 0.5);
        let y = 80 + index * 52;
        let width = value / maximum * 580.0;
        let color = if backend == "git" {
            "#94a3b8"
        } else {
            "#34d399"
        };
        svg.push_str(&format!("<text x=\"24\" y=\"{}\" font-size=\"13\">{} · {} in flight</text><rect x=\"180\" y=\"{y}\" width=\"{width:.1}\" height=\"27\" rx=\"3\" fill=\"{color}\"/><text x=\"{:.1}\" y=\"{}\" font-size=\"13\">{value:.2} ms</text>", y + 19, escape(backend), concurrency, 188.0 + width, y + 19));
        if samples.errors + samples.incorrect > 0 {
            svg.push_str(&format!("<text x=\"180\" y=\"{}\" font-size=\"11\" fill=\"#f87171\">INVALID: {} errors / {} incorrect</text>", y + 42, samples.errors, samples.incorrect));
        }
    }
    svg.push_str("</g></svg>\n");
    fs::write(path.with_extension("svg"), svg)?;
    fs::write(path.with_extension("summary.md"), &markdown)?;
    print!("{markdown}");
    Ok(())
}
fn escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}
fn percentile(values: &[f64], fraction: f64) -> f64 {
    if values.is_empty() {
        return 0.0;
    }
    let mut sorted = values.to_vec();
    sorted.sort_by(f64::total_cmp);
    sorted[((sorted.len() as f64 * fraction).ceil() as usize)
        .saturating_sub(1)
        .min(sorted.len() - 1)]
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn uses_nearest_rank_percentiles() {
        assert_eq!(percentile(&[4.0, 1.0, 2.0, 3.0], 0.5), 2.0);
        assert_eq!(percentile(&[4.0, 1.0, 2.0, 3.0], 0.99), 4.0);
    }
}
